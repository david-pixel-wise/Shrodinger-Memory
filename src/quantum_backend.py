#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
Backend abstraction layer.

Every game file calls only the two functions below; neither the deck
generator nor the Bloch popup code needs to know whether it is talking
to the local Aer simulator or a real IBM Quantum processor. The choice
is entirely controlled by config.BACKEND_MODE.

    run_deck_circuit(qc)             -> a 4-bit outcome string, used to
                                         build the card deck.
    get_bloch_vectors(qc, n_qubits)  -> (vectors, statevector)
                                         exactly one of the two is None:
                                           - simulator: vectors is None,
                                             statevector is exact.
                                           - ibm: statevector is None,
                                             vectors are per-qubit Bloch
                                             vectors *estimated* from
                                             measured <X>,<Y>,<Z>.
    get_entanglement_witness(qc)     -> ibm-mode only: an approximate
                                         entanglement witness computed
                                         from the <XX>,<YY>,<ZZ> two-qubit
                                         correlators (real hardware can't
                                         give an exact concurrence, since
                                         that needs the full density
                                         matrix, not just marginals).
    get_noise_index(qc, measured_vectors, n_qubits)
                                      -> ibm-mode only: 0-100% deviation
                                         of the real, measured per-qubit
                                         Bloch vectors from the ideal
                                         (noiseless simulator) prediction
                                         for the same circuit -- a simple
                                         "how far did the real QPU stray"
                                         indicator, no extra hardware
                                         calls needed.
    marginal_bloch_vectors_from_statevector(statevec, n_qubits)
                                      -> simulator-mode helper: exact
                                         per-qubit [<X>,<Y>,<Z>] vectors
                                         computed from a full statevector,
                                         so simulator figures can be built
                                         panel-by-panel just like ibm-mode
                                         figures are.
    get_basis_probabilities(qc, n_qubits)
                                      -> works in both modes: joint
                                         probability distribution over
                                         computational-basis outcomes,
                                         used for the probability bar
                                         chart and correlation heatmap
                                         panels (see edu_viz.py).
    safe_concurrence(statevec)       -> like qiskit's concurrence(), but
                                         clips NaN/floating-point noise
                                         near the 0 and 1 boundaries to a
                                         clean [0, 1] value. concurrence()
                                         can return NaN (sqrt of a tiny
                                         negative number) for states very
                                         close to unentangled -- this
                                         happens for real inputs, not just
                                         edge cases, so every call site
                                         uses this instead of the raw
                                         qiskit function.
    generate_random_angle(low, high, n_bits)
                                      -> a genuinely quantum-random float
                                         in [low, high), generated by
                                         measuring n_bits qubits prepared
                                         in superposition (same spirit as
                                         the rest of the game's deck
                                         generation). Used to give each
                                         emoji pair a fixed, quantum-random
                                         angle at deck-build time.
"""

import config
from qiskit_aer import AerSimulator

_service = None
_backend = None


def _get_ibm_backend():
    """Lazily connect to IBM Quantum and cache the chosen backend."""
    global _service, _backend
    if _backend is None:
        from qiskit_ibm_runtime import QiskitRuntimeService
        _service = QiskitRuntimeService(
            channel=config.IBM_CHANNEL,
            instance=config.IBM_INSTANCE,
            token=config.IBM_TOKEN,
        )
        if config.IBM_BACKEND:
            _backend = _service.backend(config.IBM_BACKEND)
        else:
            _backend = _service.least_busy(operational=True, simulator=False)
    return _backend


def run_deck_circuit(qc):
    """
    Run a measurement-only circuit (used for deck generation) and return
    one bitstring. Works unchanged on both simulator and real hardware,
    since this only ever needed measurement counts, never a statevector.
    """
    if config.BACKEND_MODE == "ibm":
        from qiskit import transpile
        from qiskit_ibm_runtime import SamplerV2 as Sampler

        backend = _get_ibm_backend()
        tqc = transpile(qc, backend)
        sampler = Sampler(backend)
        job = sampler.run([tqc], shots=1)
        result = job.result()[0]
        # SamplerV2 result -> bitstrings keyed by the classical register name
        creg_name = qc.cregs[0].name
        bits = getattr(result.data, creg_name).get_bitstrings()[0]
        return bits
    else:
        sim = AerSimulator(method='statevector')
        sim.set_options(shots=1)
        result = sim.run(qc).result()
        return next(iter(result.get_counts(qc)))


def get_bloch_vectors(qc_no_measure, n_qubits=2):
    """
    qc_no_measure: a QuantumCircuit with NO measure/save_statevector
    instructions appended (the caller only builds the entangling gates).

    Returns (vectors, statevector):
      - simulator mode: (None, exact_statevector)
      - ibm mode:        (list_of_[x,y,z]_per_qubit, None)
    """
    if config.BACKEND_MODE == "ibm":
        from qiskit import transpile
        from qiskit.quantum_info import SparsePauliOp
        from qiskit_ibm_runtime import EstimatorV2 as Estimator

        backend = _get_ibm_backend()
        tqc = transpile(qc_no_measure, backend)
        estimator = Estimator(backend)
        estimator.options.default_shots = config.IBM_SHOTS

        # The transpiled circuit spans the whole device (e.g. 156 qubits),
        # so each 2-qubit observable must be remapped onto the physical
        # qubits the transpiler chose. All observables go in one job.
        obs = []
        for q in range(n_qubits):
            for p in "XYZ":
                label = ["I"] * n_qubits
                label[q] = p
                obs.append(SparsePauliOp("".join(reversed(label))).apply_layout(tqc.layout))
        job = estimator.run([(tqc, obs)])
        evs = [float(v) for v in job.result()[0].data.evs]
        vectors = [evs[3 * q: 3 * q + 3] for q in range(n_qubits)]
        return vectors, None
    else:
        qc2 = qc_no_measure.copy()
        qc2.save_statevector()
        sim = AerSimulator(method='statevector')
        result = sim.run(qc2).result()
        try:
            statevec = result.get_statevector()
        except Exception:
            statevec = result.data(0)['statevector']
        return None, statevec


def get_entanglement_witness(qc_no_measure):
    """
    ibm-mode only helper: estimate |<XX>| + |<YY>| + |<ZZ>| on real
    hardware as an approximate entanglement witness. For a noiseless
    Bell-type state this equals 3.0 (maximally entangled); real hardware
    noise will pull it below that. Not the same quantity as concurrence,
    but a good "how entangled does this look" indicator when an exact
    density matrix isn't available.
    """
    from qiskit import transpile
    from qiskit.quantum_info import SparsePauliOp
    from qiskit_ibm_runtime import EstimatorV2 as Estimator

    backend = _get_ibm_backend()
    tqc = transpile(qc_no_measure, backend)
    estimator = Estimator(backend)
    estimator.options.default_shots = config.IBM_SHOTS

    obs = [SparsePauliOp(l).apply_layout(tqc.layout) for l in ("XX", "YY", "ZZ")]
    job = estimator.run([(tqc, obs)])
    evs = job.result()[0].data.evs
    return sum(abs(float(v)) for v in evs)


def get_noise_index(qc_no_measure, measured_vectors, n_qubits=2):
    """
    ibm-mode only helper: quantifies how far a real QPU's results strayed
    from the noiseless prediction for the SAME circuit. Compares the
    already-measured per-qubit Bloch vectors (fetched via EstimatorV2 on
    real hardware -- the caller already has these, no new hardware calls
    needed here) against the exact vectors an ideal, noiseless simulator
    gives for the identical circuit (computed locally, instantly, via
    Statevector -- also no hardware call).

    Returns a 0-100 percentage: 0% means the real hardware matched the
    ideal simulation exactly for every qubit; 100% is the theoretical
    worst case (every measured vector exactly antipodal to its ideal
    counterpart -- Euclidean distance 2.0 between two unit vectors is the
    maximum possible). Real hardware noise typically lands well below
    that ceiling, but there's no fixed "acceptable" threshold -- it
    depends on the specific QPU, calibration, and circuit depth.
    """
    from qiskit.quantum_info import Statevector

    ideal_sv = Statevector(qc_no_measure)
    ideal_vectors = marginal_bloch_vectors_from_statevector(ideal_sv, n_qubits)

    distances = []
    for measured, ideal in zip(measured_vectors, ideal_vectors):
        dist = sum((m - i) ** 2 for m, i in zip(measured, ideal)) ** 0.5
        distances.append(dist)

    avg_distance = sum(distances) / len(distances)
    return (avg_distance / 2.0) * 100.0


def marginal_bloch_vectors_from_statevector(statevec, n_qubits=2):
    """
    Simulator-mode helper: compute each qubit's exact reduced Bloch vector
    [<X>,<Y>,<Z>] directly from a full statevector, so simulator-mode figures
    can plot per-qubit Bloch spheres with plot_bloch_vector(ax=...) the same
    way the ibm-mode branch already does -- letting both branches share one
    combined-figure layout (Bloch spheres + an extra educational panel)
    instead of the whole-figure plot_bloch_multivector() that leaves no room
    to add anything else to the same popup.
    """
    from qiskit.quantum_info import Statevector, SparsePauliOp

    sv = Statevector(statevec)
    vectors = []
    for q in range(n_qubits):
        vec = []
        for p in "XYZ":
            label = ["I"] * n_qubits
            label[q] = p
            op = SparsePauliOp("".join(reversed(label)))
            vec.append(float(sv.expectation_value(op).real))
        vectors.append(vec)
    return vectors


def get_basis_probabilities(qc_no_measure, n_qubits=2):
    """
    Backend-agnostic joint probability distribution over computational
    basis outcomes ('00', '01', '10', '11', ...) -- used by the
    probability bar chart and correlation heatmap panels, which stay
    identical whether the numbers came from an exact statevector
    (simulator) or from real measurement counts (ibm mode).
    """
    if config.BACKEND_MODE == "ibm":
        from qiskit import transpile
        from qiskit_ibm_runtime import SamplerV2 as Sampler

        backend = _get_ibm_backend()
        qc = qc_no_measure.copy()
        qc.measure_all()
        tqc = transpile(qc, backend)
        sampler = Sampler(backend)
        job = sampler.run([tqc], shots=config.IBM_SHOTS)
        result = job.result()[0]
        counts = result.data.meas.get_counts()
        total = sum(counts.values())
        return {bits.replace(" ", ""): n / total for bits, n in counts.items()}
    else:
        from qiskit.quantum_info import Statevector

        sv = Statevector(qc_no_measure)
        return sv.probabilities_dict()


def get_pauli_correlators(qc_no_measure):
    """
    Backend-agnostic <XX>, <YY>, <ZZ> two-qubit correlators. Some
    entangled states (e.g. Experiment 5's H+H+CZ construction) have a perfectly
    flat computational-basis probability distribution -- the correlation
    is only visible by measuring in a different basis, which is exactly
    what this exposes. Works in both modes: exact expectation values from
    the statevector on the simulator, estimated values from real hardware
    via EstimatorV2 in ibm mode.
    """
    if config.BACKEND_MODE == "ibm":
        from qiskit import transpile
        from qiskit.quantum_info import SparsePauliOp
        from qiskit_ibm_runtime import EstimatorV2 as Estimator

        backend = _get_ibm_backend()
        tqc = transpile(qc_no_measure, backend)
        estimator = Estimator(backend)
        estimator.options.default_shots = config.IBM_SHOTS
        obs = [SparsePauliOp(l).apply_layout(tqc.layout) for l in ("XX", "YY", "ZZ")]
        job = estimator.run([(tqc, obs)])
        evs = job.result()[0].data.evs
        return {"XX": float(evs[0]), "YY": float(evs[1]), "ZZ": float(evs[2])}
    else:
        from qiskit.quantum_info import Statevector, SparsePauliOp

        sv = Statevector(qc_no_measure)
        return {
            lbl: float(sv.expectation_value(SparsePauliOp(lbl)).real)
            for lbl in ("XX", "YY", "ZZ")
        }


def safe_concurrence(statevec):
    """
    qiskit's concurrence() can return NaN for states very close to
    unentangled: it computes sqrt(2*(1 - purity)), and floating-point
    rounding can push purity fractionally above 1.0, making the sqrt
    argument a tiny negative number. Confirmed this happens for genuine,
    unremarkable product states (not just contrived edge cases), so every
    concurrence call in this codebase goes through this wrapper instead
    of calling qiskit's concurrence() directly.

    The NaN itself is harmless -- clipped to 0.0 below -- but numpy still
    prints a RuntimeWarning ("invalid value encountered in sqrt") to the
    console the moment it happens, from inside qiskit's own code, before
    this function gets a chance to clip anything. That's just noise for
    an already-handled case, so it's suppressed locally here rather than
    left to alarm anyone running the game from a terminal.
    """
    import math
    import warnings
    from qiskit.quantum_info import Statevector, concurrence

    with warnings.catch_warnings():
        warnings.filterwarnings("ignore", message="invalid value encountered in sqrt")
        c = concurrence(Statevector(statevec))

    c = float(c)
    if math.isnan(c):
        c = 0.0
    return max(0.0, min(1.0, c))


def generate_random_angle(low=0.0, high=None, n_bits=8):
    """
    A genuinely quantum-random float in [low, high), generated by
    preparing n_bits qubits in equal superposition and measuring them --
    the same mechanism the game already uses to build the card deck
    itself (see make_card_circuit), just reused here to pick a fixed
    angle once per emoji at deck-build time. Works on both simulator and
    real IBM hardware via run_deck_circuit(), so no separate backend
    branching is needed here.
    """
    import math
    from qiskit import QuantumCircuit

    if high is None:
        high = math.pi

    qc = QuantumCircuit(n_bits, n_bits)
    qc.h(range(n_bits))
    qc.measure(range(n_bits), range(n_bits))
    bits = run_deck_circuit(qc)
    frac = int(bits, 2) / (2 ** n_bits - 1)
    return low + frac * (high - low)
